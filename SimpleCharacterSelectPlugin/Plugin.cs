        private void ApplyLastUsedCharacter(string fullKey)
        {
            // Prevent AutoLoad-LastUsed from running multiple times during startup
            // TODO ^ ...what?
            if (autoLoadAlreadyRanThisStartup)
            {
                return;
            }
            autoLoadAlreadyRanThisStartup = true;

            // First check for specific character assignment
            if (Configuration.CharacterAssignments.TryGetValue(fullKey, out var assignmentValue))
            {
                // Check if assignment is "None" - skip all auto-application
                if (assignmentValue == "None")
                {
                    Plugin.Log.Debug($"[AutoLoad-Assignment] ⚠ Assignment set to 'None' for {fullKey} - skipping all auto-application");
                    lastAppliedCharacter = fullKey;
                    assignmentAppliedForCharacter = fullKey;
                    return;
                }

                // Parse the assignment to get character name and optional design name
                var (assignedCharacterName, assignedDesignName) = ParseCharacterAssignment(assignmentValue);

                var assignedCharacter = Characters.FirstOrDefault(c => c.Data.Name == assignedCharacterName);
                if (assignedCharacter != null)
                {
                    int designIndex;
                    if (!string.IsNullOrEmpty(assignedDesignName))
                    {
                        // Use specified design from assignment
                        designIndex = assignedCharacter.Data.Designs.FindIndex(d => d.Name == assignedDesignName);
                        if (designIndex < 0)
                        {
                            Plugin.Log.Warning($"[AutoLoad-Assignment] Design '{assignedDesignName}' not found, using last used design");
                            designIndex = GetLastUsedDesignIndex(assignedCharacter);
                        }
                        else
                        {
                            Plugin.Log.Debug($"[AutoLoad-Assignment] Using assigned design: {assignedDesignName}");
                        }
                    }
                    else
                    {
                        // No design specified, use last used
                        designIndex = GetLastUsedDesignIndex(assignedCharacter);
                    }

                    Plugin.Log.Debug($"[AutoLoad-Assignment] ✅ Applying assigned character {assignedCharacter.Data.Name} for {fullKey} (design index: {designIndex})");
                    ApplyProfile(assignedCharacter, designIndex);
                    lastAppliedCharacter = fullKey;
                    assignmentAppliedForCharacter = fullKey;
                    characterAlreadyAppliedOnStartup = true; // Mark as handled // TODO are you twelve?
                    return;
                }
                else
                {
                    Plugin.Log.Debug($"[AutoLoad-Assignment] ❌ Assigned character '{assignedCharacterName}' not found for {fullKey}");
                    // Remove invalid assignment (but keep "None" assignments)
                    Configuration.CharacterAssignments.Remove(fullKey);
                    Configuration.Save();
                }
            }

            // Fall back to existing "last used" logic
            if (Configuration.LastUsedCharacterByPlayer.TryGetValue(fullKey, out var lastUsedKey))
            {
                var character = Characters.FirstOrDefault(c =>
                    $"{c.Data.Name}@{ObjectTable.LocalPlayer!.HomeWorld.Value.Name}" == lastUsedKey);

                if (character != null)
                {
                    Plugin.Log.Debug($"[AutoLoad-LastUsed] ✅ Applying {character.Data.Name} for {fullKey}");
                    int designIndex = GetLastUsedDesignIndex(character);
                    Plugin.Log.Debug($"[AutoLoad-LastUsed] Design index for {character.Data.Name}: {designIndex}");
                    ApplyProfile(character, designIndex);
                    lastAppliedCharacter = fullKey;
                    characterAlreadyAppliedOnStartup = true; // Mark as handled
                }
                else
                {
                    // Recovery: if value equals key (corrupted by old SetActiveCharacter bug),
                    // try to find character via LastUsedCharacterKey or session_info.txt
                    Character? recovered = null;
                    if (lastUsedKey == fullKey)
                    {
                        Plugin.Log.Debug($"[AutoLoad-LastUsed] Detected corrupted entry (value=key), attempting recovery");

                        // Try LastUsedCharacterKey first
                        if (!string.IsNullOrEmpty(Configuration.LastUsedCharacterKey))
                        {
                            recovered = Characters.FirstOrDefault(c =>
                                c.Data.Name.Equals(Configuration.LastUsedCharacterKey, StringComparison.OrdinalIgnoreCase));
                        }

                        // Try session_info.txt
                        if (recovered == null && _pendingSessionCharacterName != null)
                        {
                            recovered = Characters.FirstOrDefault(c =>
                                c.Data.Name.Equals(_pendingSessionCharacterName, StringComparison.OrdinalIgnoreCase));
                        }
                    }

                    if (recovered != null)
                    {
                        Plugin.Log.Debug($"[AutoLoad-LastUsed] ✅ Recovered: applying {recovered.Data.Name} for {fullKey}");
                        int designIndex = GetLastUsedDesignIndex(recovered);
                        ApplyProfile(recovered, designIndex);
                        lastAppliedCharacter = fullKey;
                        characterAlreadyAppliedOnStartup = true;
                    }
                    else if (lastAppliedCharacter != $"!notfound:{lastUsedKey}")
                    {
                        Plugin.Log.Debug($"[AutoLoad-LastUsed] ❌ No match found for {lastUsedKey}");
                        lastAppliedCharacter = $"!notfound:{lastUsedKey}";
                    }
                }
            }
            else
            {
                Plugin.Log.Debug($"[AutoLoad] ❌ No assignment or previous character stored for {fullKey}");
            }
        }
        
        private int GetLastUsedDesignIndex(Character character)
        {
            // Return -1 (no design) if design auto-reapplication is disabled
            // TODO if it's disabled just don't run the method lmao
            if (!Configuration.EnableLastUsedDesignAutoload)
            {
                Plugin.Log.Debug($"[AutoLoad-Design] Design auto-reapplication is disabled");
                return -1;
            }
            
            Plugin.Log.Debug($"[AutoLoad-Design] Design auto-reapplication is ENABLED for {character.Data.Name}");
            
            // Try to get the last used design for this character
            if (Configuration.LastUsedDesignByCharacter.TryGetValue(character.Data.Name, out var lastDesignName))
            {
                // Find the design with the matching name
                var design = character.Data.Designs.FirstOrDefault(d => d.Name.Equals(lastDesignName, StringComparison.OrdinalIgnoreCase));
                if (design != null)
                {
                    int designIndex = character.Data.Designs.IndexOf(design);
                    Plugin.Log.Debug($"[AutoLoad-Design] ✅ Found last used design '{lastDesignName}' at index {designIndex} for {character.Data.Name}");
                    return designIndex;
                }
                else
                {
                    Plugin.Log.Debug($"[AutoLoad-Design] ❌ Last used design '{lastDesignName}' not found for {character.Data.Name}");
                }
            }
            else
            {
                Plugin.Log.Debug($"[AutoLoad-Design] ❌ No last used design stored for {character.Data.Name}");
            }
            
            return -1; // No design or not found
        }
        
