                    macroLines.Add($"/glamourer apply \"{design.Name}\" to self");
                }
                else
                {
                    // Use standard Glamourer apply
                    macroLines.Add($"/glamourer apply \"{design.Name}\" to self");
                }
            }

            // Add Customize+ apply if we have it
            if (!string.IsNullOrEmpty(design.CustomizePlusProfile))
