                ? new List<string>()
                : NewCharacterTag.Split(',').Select(f => f.Trim()).ToList(),
                    SecretModState = NewSecretModState,
                    SecretModPins = NewSecretModPins,
                    AssignedGearset = NewCharacterGearset
                };

